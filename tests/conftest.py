CallServer = Callable[..., SoapResponse]
"""Signature of the ``call_server`` fixture."""


@pytest.fixture
def call_server(client: SplashClient, codec: MessageCodec) -> CallServer:
    """Send a request to the client as the Splash server would (PHP SoapClient envelope)."""

